/*
 * Runtime support for recompiled PSP (Allegrex/MIPS) code.
 *
 * Every recompiled function has the signature `void fn(Ctx *c)`: the MIPS
 * register file lives in Ctx and is passed along, exactly like the real CPU
 * state is "passed" from one function to the next on the PSP.
 */
#pragma once

#include <setjmp.h>
#include <stdint.h>
#include <string.h>

typedef struct Ctx {
    uint32_t r[32];          /* general purpose registers, r[0] always 0 */
    uint32_t hi, lo;         /* multiply / divide results */
    union {                  /* FPU registers: viewed as float or as raw bits */
        float f[32];
        uint32_t fi[32];
    };
    uint32_t fcr31;          /* FPU control/status */
    int fcc;                 /* FPU condition flag (set by c.*.s, read by bc1t/bc1f) */
    float v[128];            /* VFPU registers: v[matrix*16 + column*4 + row] */
    uint32_t vctrl[16];      /* VFPU control: 0-2 S/T/D prefixes, 3 condition codes, ... */
} Ctx;

/* A fresh register file. The VFPU prefixes must start as "identity" (0xE4:
 * lanes x,y,z,w in order); an all-zero prefix would mean "every lane reads x". */
static inline void rt_ctx_init(Ctx *c) {
    memset(c, 0, sizeof *c);
    c->vctrl[0] = c->vctrl[1] = 0xE4;
}

typedef void (*RecompFn)(Ctx *c);

typedef struct {
    uint32_t addr;
    RecompFn fn;
    const char *name;
} RecompFnEntry;

/* ---- generated by tools/recomp.py ---- */
extern const RecompFnEntry rt_func_table[];   /* sorted by addr */
extern const uint32_t rt_func_table_len;
extern const uint32_t rt_image_base;          /* where the program's memory image starts */
extern const uint32_t rt_image_size;
extern const uint32_t rt_entry;               /* program entry point (_start) */

/* ---- memory ----
 * The PSP has a 32-bit address space with mirrors: 0x08000000 (RAM) is also
 * visible at 0x48000000 (uncached), VRAM 0x04000000 at 0x44000000. Masking
 * with 0x3FFFFFFF folds the mirrors, so one 1 GiB host reservation covers
 * everything and a guest address becomes a host pointer with one AND + ADD.
 */
extern uint8_t *rt_mem;
#define RT_MEM_MASK 0x3FFFFFFFu

static inline uint8_t *rt_ptr(uint32_t addr) { return rt_mem + (addr & RT_MEM_MASK); }

/* Guest and host are both little-endian, so values are copied as-is.
 * memcpy keeps the compiler honest about alignment and aliasing. */
static inline uint32_t MEM_LW(uint32_t a)  { uint32_t v; memcpy(&v, rt_ptr(a), 4); return v; }
static inline uint32_t MEM_LH(uint32_t a)  { int16_t v;  memcpy(&v, rt_ptr(a), 2); return (uint32_t)(int32_t)v; }
static inline uint32_t MEM_LHU(uint32_t a) { uint16_t v; memcpy(&v, rt_ptr(a), 2); return v; }
static inline uint32_t MEM_LB(uint32_t a)  { return (uint32_t)(int32_t)(int8_t)*rt_ptr(a); }
static inline uint32_t MEM_LBU(uint32_t a) { return *rt_ptr(a); }
static inline void MEM_SW(uint32_t a, uint32_t v) { memcpy(rt_ptr(a), &v, 4); }
static inline void MEM_SH(uint32_t a, uint32_t v) { uint16_t h = (uint16_t)v; memcpy(rt_ptr(a), &h, 2); }
static inline void MEM_SB(uint32_t a, uint32_t v) { *rt_ptr(a) = (uint8_t)v; }

/* Unaligned word access, little-endian MIPS (lwl/lwr/swl/swr).
 * A compiler emits a pair (lwl at addr+3, lwr at addr) to load an unaligned
 * word; each one fills in part of the register from the aligned word. */
static inline uint32_t MEM_LWL(uint32_t rt, uint32_t a) {
    uint32_t sh = a & 3, w = MEM_LW(a & ~3u);
    return (rt & (0x00FFFFFFu >> (sh * 8))) | (w << ((3 - sh) * 8));
}
static inline uint32_t MEM_LWR(uint32_t rt, uint32_t a) {
    uint32_t sh = a & 3, w = MEM_LW(a & ~3u);
    return (rt & (0xFFFFFF00u << ((3 - sh) * 8))) | (w >> (sh * 8));
}
static inline void MEM_SWL(uint32_t a, uint32_t rt) {
    uint32_t sh = a & 3, w = MEM_LW(a & ~3u);
    MEM_SW(a & ~3u, (w & (0xFFFFFF00u << (sh * 8))) | (rt >> ((3 - sh) * 8)));
}
static inline void MEM_SWR(uint32_t a, uint32_t rt) {
    uint32_t sh = a & 3, w = MEM_LW(a & ~3u);
    MEM_SW(a & ~3u, (w & (0x00FFFFFFu >> ((3 - sh) * 8))) | (rt << (sh * 8)));
}

/* ---- ALU helpers ---- */
static inline uint32_t ROTR(uint32_t x, uint32_t n) { n &= 31; return n ? (x >> n) | (x << (32 - n)) : x; }
static inline uint32_t CLZ(uint32_t x) { return x ? (uint32_t)__builtin_clz(x) : 32; }
static inline uint32_t EXT(uint32_t x, uint32_t pos, uint32_t size) {
    return (x >> pos) & (size == 32 ? 0xFFFFFFFFu : (1u << size) - 1);
}
static inline uint32_t INS(uint32_t rt, uint32_t rs, uint32_t pos, uint32_t size) {
    uint32_t mask = (size == 32 ? 0xFFFFFFFFu : (1u << size) - 1) << pos;
    return (rt & ~mask) | ((rs << pos) & mask);
}
static inline uint32_t WSBH(uint32_t x) { return ((x & 0x00FF00FFu) << 8) | ((x >> 8) & 0x00FF00FFu); }
static inline uint32_t BITREV(uint32_t x) {
    uint32_t r = 0;
    for (int i = 0; i < 32; i++) r |= ((x >> i) & 1u) << (31 - i);
    return r;
}

static inline void MULT(Ctx *c, uint32_t a, uint32_t b) {
    int64_t p = (int64_t)(int32_t)a * (int32_t)b;
    c->lo = (uint32_t)p; c->hi = (uint32_t)((uint64_t)p >> 32);
}
static inline void MULTU(Ctx *c, uint32_t a, uint32_t b) {
    uint64_t p = (uint64_t)a * b;
    c->lo = (uint32_t)p; c->hi = (uint32_t)(p >> 32);
}
/* madd/msub accumulate into hi:lo (PSP-specific location in the SPECIAL table). */
static inline void MADD(Ctx *c, int64_t p) {
    uint64_t acc = (((uint64_t)c->hi << 32) | c->lo) + (uint64_t)p;
    c->lo = (uint32_t)acc; c->hi = (uint32_t)(acc >> 32);
}
/* Division by zero doesn't trap on MIPS; the result registers just get
 * "something". These values are placeholders.
 * TODO(phase 7): check against PPSSPP's interpreter / hardware tests. */
static inline void DIV(Ctx *c, uint32_t a, uint32_t b) {
    int32_t x = (int32_t)a, y = (int32_t)b;
    if (y == 0) { c->hi = a; c->lo = x < 0 ? 1 : 0xFFFFFFFFu; }
    else if (x == INT32_MIN && y == -1) { c->lo = 0x80000000u; c->hi = 0; }
    else { c->lo = (uint32_t)(x / y); c->hi = (uint32_t)(x % y); }
}
static inline void DIVU(Ctx *c, uint32_t a, uint32_t b) {
    if (b == 0) { c->hi = a; c->lo = 0xFFFFFFFFu; }
    else { c->lo = a / b; c->hi = a % b; }
}

/* ---- FPU helpers ----
 * Allegrex FPU = IEEE single precision, same as a host `float`. Generated
 * code must be compiled with -ffp-contract=off: the PSP has no fused
 * multiply-add, so `a*b + c` must round twice, like the original. */

/* float -> int with the four MIPS rounding modes (fcr31 bits 0-1).
 * Out of range and NaN give 0x7FFFFFFF, the MIPS "invalid" result
 * (in C it would be undefined behaviour). */
static inline uint32_t CVT_W_S(float x, uint32_t mode) {
    if (x != x || x >= 2147483648.0f || x < -2147483648.0f) return 0x7FFFFFFFu;
    float r;
    switch (mode & 3) {
    case 0: r = __builtin_rintf(x); break;    /* round to nearest even */
    case 1: r = __builtin_truncf(x); break;   /* toward zero */
    case 2: r = __builtin_ceilf(x); break;    /* toward +inf */
    default: r = __builtin_floorf(x); break;  /* toward -inf */
    }
    if (r >= 2147483648.0f) return 0x7FFFFFFFu;
    return (uint32_t)(int32_t)r;
}

/* c.cond.s: the low 4 bits of funct say which relations make it true.
 * bit 0 = unordered (a NaN is involved), bit 1 = equal, bit 2 = less than.
 * (bit 3 only decides whether NaNs raise an exception; ignored.) */
static inline int FCMP(float a, float b, uint32_t cond) {
    if (a != a || b != b) return cond & 1;
    return ((cond & 2) && a == b) || ((cond & 4) && a < b);
}

/* cfc1/ctc1: fcr31 holds the condition flag in bit 23. */
static inline uint32_t CFC1(Ctx *c, uint32_t reg) {
    if (reg == 31) return (c->fcr31 & ~(1u << 23)) | ((uint32_t)c->fcc << 23);
    return 0;   /* FIR (implementation register): no features to report */
}
static inline void CTC1(Ctx *c, uint32_t reg, uint32_t v) {
    if (reg == 31) { c->fcr31 = v; c->fcc = (v >> 23) & 1; }
}

/* ---- profiling ----
 * Every recompiled function records its own address on entry. Only one game
 * thread runs at a time, so one global is enough; MKU_PROFILE=1 samples it. */
extern volatile uint32_t rt_cur_fn;

/* Shadow call stack: which recompiled functions are active, per PSP thread or
 * process fiber (whoever runs now owns rt_shadow). The cleanup attribute pops
 * the entry on every return path. Used by the hang/timeout dumps. */
#define RT_SHADOW_MAX 128
typedef struct { uint32_t fn[RT_SHADOW_MAX]; int depth; } RtShadow;
extern RtShadow *rt_shadow;
static inline void rt_shadow_pop(int *depth) { rt_shadow->depth = *depth; }
#ifdef RT_COVERAGE   /* make COVER=1 + MKU_COVER="from,to": which functions ran between two frames */
extern uint8_t rt_cover[];
#define RT_COVER_MARK(addr) (rt_cover[((addr) - 0x08800000u) >> 2] = 1)
#else
#define RT_COVER_MARK(addr) ((void)0)
#endif
#define RT_ENTER(addr) \
    int rt_depth_ __attribute__((cleanup(rt_shadow_pop), unused)) = rt_shadow->depth; \
    if (rt_depth_ < RT_SHADOW_MAX) rt_shadow->fn[rt_depth_] = (addr); \
    rt_shadow->depth = rt_depth_ + 1; \
    RT_COVER_MARK(addr); \
    rt_cur_fn = (addr)
void rt_shadow_print(const RtShadow *s, const char *indent);

