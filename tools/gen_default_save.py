"""Turn a save holding one fresh profile into runtime/patches/default_save.inc.

The save is 262,680 bytes, 99.9% zeros: default settings, the name PLAYER 1 and
its kode (the cross button six times). No art or sound. This keeps just the
non-zero runs, as a C table. Only needed to regenerate the table:

    python3 -I tools/gen_default_save.py saves/PSP/SAVEDATA/ULUS10102MKU0000/DATA.BIN
"""
import sys

GAP = 16   # join runs separated by fewer zeros than a new table entry would cost


def main():
    d = open(sys.argv[1], "rb").read()
    runs, i = [], 0
    while i < len(d):
        if d[i] == 0:
            i += 1
            continue
        j = i + 1
        end = i + 1
        while j < len(d) and j - end < GAP:
            if d[j]:
                end = j + 1
            j += 1
        runs.append((i, d[i:end]))
        i = end
    with open("runtime/patches/default_save.inc", "w") as f:
        f.write(f"/* Generated by tools/gen_default_save.py: non-zero parts of a save with one fresh profile. */\n")
        f.write(f"#define DEFAULT_SAVE_SIZE {len(d)}u\n")
        for k, (_, b) in enumerate(runs):
            f.write(f"static const uint8_t k_run{k}[] = {{")
            f.write(",".join(str(x) for x in b))
            f.write("};\n")
        f.write("static const struct { uint32_t offset, size; const uint8_t *bytes; } k_default_save[] = {\n")
        for k, (o, b) in enumerate(runs):
            f.write(f"    {{{o}, {len(b)}, k_run{k}}},\n")
        f.write("};\n")
    print(f"{len(runs)} runs, {sum(len(b) for _, b in runs)} bytes of {len(d)}")


if __name__ == "__main__":
    main()
